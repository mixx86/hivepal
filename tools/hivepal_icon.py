"""Generates the Hivepal icon: a rounded honeycomb hexagon with a face (eyes and smile cut out)
and two bee antennae. Writes the Android adaptive-icon foreground and an SVG/PNG preview."""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CX, CY, R, ROUND = 54.0, 58.0, 21.0, 4.2
#: Everything fits the adaptive-icon safe zone (a 66dp circle) at this scale.
SCALE = 1.08


def hexagon() -> str:
    pts = [(CX + R * math.cos(math.radians(a)), CY + R * math.sin(math.radians(a))) for a in range(-90, 270, 60)]
    d = []
    n = len(pts)
    for i in range(n):
        p0, p1, p2 = pts[i - 1], pts[i], pts[(i + 1) % n]

        def toward(a, b, dist):
            l = math.dist(a, b)
            return (a[0] + (b[0] - a[0]) * dist / l, a[1] + (b[1] - a[1]) * dist / l)

        s, e = toward(p1, p0, ROUND), toward(p1, p2, ROUND)
        d.append(("M" if i == 0 else "L") + f"{s[0]:.2f},{s[1]:.2f}")
        d.append(f"Q{p1[0]:.2f},{p1[1]:.2f} {e[0]:.2f},{e[1]:.2f}")
    return "".join(d) + "Z"


def circle(x, y, r) -> str:
    return f"M{x - r:.2f},{y:.2f}a{r},{r} 0,1 0,{2 * r:.2f},0a{r},{r} 0,1 0,{-2 * r:.2f},0Z"


FACE = (
    hexagon()
    + circle(47.0, 56.0, 3.0)
    + circle(61.0, 56.0, 3.0)
    # smile: a thin crescent
    + "M46.5,63.2Q54,71.5 61.5,63.2Q54,67.6 46.5,63.2Z"
)
ANTENNAE = ["M49,39.5Q46.5,31 41,27.5", "M59,39.5Q61.5,31 67,27.5"]
TIPS = [circle(40.2, 26.8, 3.0), circle(67.8, 26.8, 3.0)]


def android(color: str = "#FFFFFFFF") -> str:
    parts = [f'    <path android:fillColor="{color}" android:fillType="evenOdd" android:pathData="{FACE}" />']
    for a in ANTENNAE:
        parts.append(f'    <path android:fillColor="#00000000" android:strokeColor="{color}" android:strokeWidth="3.6" '
                     f'android:strokeLineCap="round" android:pathData="{a}" />')
    for t in TIPS:
        parts.append(f'    <path android:fillColor="{color}" android:pathData="{t}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Hivepal: a honeycomb hexagon with a face and bee antennae. Generated by tools/hivepal_icon.py. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f'  <group android:pivotX="54" android:pivotY="54" android:scaleX="{SCALE}" android:scaleY="{SCALE}">\n'
            + "\n".join(parts) + "\n  </group>\n</vector>\n")


def svg(bg: str = "#F2A21A", fg: str = "#FFFFFF", size: int = 512) -> str:
    s = size / 108
    body = [f'<path fill="{fg}" fill-rule="evenodd" d="{FACE}"/>']
    body += [f'<path fill="none" stroke="{fg}" stroke-width="3.6" stroke-linecap="round" d="{a}"/>' for a in ANTENNAE]
    body += [f'<path fill="{fg}" d="{t}"/>' for t in TIPS]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">'
            f'<rect width="108" height="108" rx="24" fill="{bg}"/>'
            f'<g transform="translate(54 54) scale({SCALE}) translate(-54 -54)">' + "".join(body) + "</g></svg>")


if __name__ == "__main__":
    res = ROOT / "app-android/app/src/main/res/drawable/ic_launcher_foreground.xml"
    res.write_text(android())
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "docs/hivepal-icon.svg"
    out.write_text(svg())
    print("wrote", res, out)
