"""Generates the Hivepal icon: a honeycomb of seven rounded cells, electric blue around a white centre,
on a dark background. Writes the Android adaptive-icon foreground and an SVG/PNG preview."""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HONEY, WHITE, DARK = "#00A6FB", "#FFFFFF", "#000814"
CELL_R, CELL_ROUND = 9.5, 2.0
#: Distance between neighbouring cell centres (flat sides almost touching, with a small gap).
STEP = CELL_R * 1.85


def hexagon(cx: float, cy: float, r: float = CELL_R, rnd: float = CELL_ROUND) -> str:
    pts = [(cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a))) for a in range(-90, 270, 60)]
    d = []
    for i in range(6):
        p0, p1, p2 = pts[i - 1], pts[i], pts[(i + 1) % 6]

        def toward(a, b, dist):
            length = math.dist(a, b)
            return (a[0] + (b[0] - a[0]) * dist / length, a[1] + (b[1] - a[1]) * dist / length)

        s, e = toward(p1, p0, rnd), toward(p1, p2, rnd)
        d.append(("M" if i == 0 else "L") + f"{s[0]:.2f},{s[1]:.2f}")
        d.append(f"Q{p1[0]:.2f},{p1[1]:.2f} {e[0]:.2f},{e[1]:.2f}")
    return "".join(d) + "Z"


def cells() -> list[tuple[str, str]]:
    """(colour, path) for the centre cell and the six around it."""
    out = [(WHITE, hexagon(54, 54))]
    for a in range(-90, 270, 60):
        out.append((HONEY, hexagon(54 + STEP * math.cos(math.radians(a)), 54 + STEP * math.sin(math.radians(a)))))
    return out


def android(monochrome: bool = False) -> str:
    parts = [f'    <path android:fillColor="{"#FFFFFFFF" if monochrome else c}" android:pathData="{p}" />' for c, p in cells()]
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Hivepal: a honeycomb of seven cells. Generated by tools/hivepal_icon.py. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            + "\n".join(parts) + "\n</vector>\n")


def svg() -> str:
    body = "".join(f'<path fill="{c}" d="{p}"/>' for c, p in cells())
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 108 108">'
            f'<rect width="108" height="108" rx="24" fill="{DARK}"/>{body}</svg>')


if __name__ == "__main__":
    res = ROOT / "app-android/app/src/main/res/drawable"
    (res / "ic_launcher_foreground.xml").write_text(android())
    (res / "ic_launcher_monochrome.xml").write_text(android(monochrome=True))
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "docs/hivepal-icon.svg"
    out.write_text(svg())
    print("wrote", res / "ic_launcher_foreground.xml", out)
